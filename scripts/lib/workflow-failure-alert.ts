/**
 * Decision logic and payload builders for cron workflow failure alerts.
 *
 * Sheet row "Alerts":
 * - Triggers on failure conclusion for scheduled cron workflows.
 * - Sends a Sentry captureMessage through the existing DSN-gated, fail-open path.
 * - Creates or updates one deduped GitHub issue per workflow per day
 *   ("Cron failure: <workflow> <date>") with the run URL.
 */

import { reportCronFailureMessage } from "./cron-sentry";

export interface WorkflowRunEvent {
  workflowName: string;
  conclusion: string;
  runUrl: string;
  runId: string | number;
  createdAt: string;
  repository?: string;
}

export interface ExistingIssueSummary {
  id?: number;
  number: number;
  title: string;
  body: string;
  state?: string;
}

export interface WorkflowAlertDeps {
  sendSentryAlert?: (cronName: string, message: string, extra?: Record<string, unknown>) => Promise<void>;
  findExistingIssue?: (title: string) => Promise<ExistingIssueSummary | null>;
  createIssue?: (title: string, body: string) => Promise<{ number: number }>;
  updateIssue?: (issueNumber: number, body: string) => Promise<{ number: number }>;
}

export interface WorkflowAlertResult {
  eligible: boolean;
  skippedReason?: string;
  sentryDispatched: boolean;
  issueAction: "created" | "updated" | "none";
  dedupeKey: string;
  issueTitle: string;
}

/**
 * Scheduled cron workflows whose failures must be proactively surfaced.
 */
export const SCHEDULED_CRON_WORKFLOWS: readonly string[] = Object.freeze([
  "Weekly Retention Purge Cron",
  "Daily Early-Access Signup Digest Cron",
  "Daily Candidate Matching & Digest Cron",
  "Dunning Outbox Dispatch Cron",
  "Capacity Headroom Report",
  "Read-only DB Health Probe",
  "Inbound Reply Poll",
  "Daily Job Ingestion & Cleanup Pipeline",
  "Plan Regression",
  "Security & Secret Scanning",
  "Source Health Monitoring",
]);

/** Check whether a workflow name matches the scheduled cron allowlist (case-insensitive). */
export function isScheduledCronWorkflow(workflowName: string): boolean {
  if (!workflowName || typeof workflowName !== "string") return false;
  const target = workflowName.trim().toLowerCase();
  return SCHEDULED_CRON_WORKFLOWS.some((w) => w.toLowerCase() === target);
}

/** Format YYYY-MM-DD from an ISO string, Date object, or epoch number. */
export function formatCronAlertDate(dateInput: string | Date | number): string {
  try {
    const d = new Date(dateInput);
    if (isNaN(d.getTime())) {
      return new Date().toISOString().slice(0, 10);
    }
    return d.toISOString().slice(0, 10);
  } catch {
    return new Date().toISOString().slice(0, 10);
  }
}

/**
 * Build the exact dedupe key / issue title:
 * "Cron failure: <workflow> <date>"
 */
export function buildCronFailureDedupeKey(workflowName: string, dateInput: string | Date | number): string {
  const safeName = (workflowName || "Unknown Workflow").trim();
  const dateStr = formatCronAlertDate(dateInput);
  return `Cron failure: ${safeName} ${dateStr}`;
}

/**
 * Build the Sentry captureMessage payload and metadata.
 */
export function buildSentryAlertMessage(event: WorkflowRunEvent): {
  cronTag: string;
  message: string;
  extra: Record<string, unknown>;
} {
  const cronTag = event.workflowName.toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^-|-$/g, "");
  const message = `Cron workflow failure: ${event.workflowName} (run ${event.runId})`;
  const extra: Record<string, unknown> = {
    workflowName: event.workflowName,
    runConclusion: event.conclusion,
    runUrl: event.runUrl,
    runId: event.runId,
    createdAt: event.createdAt,
    repository: event.repository || "ORM-git/Carrier-hound",
  };
  return { cronTag, message, extra };
}

/**
 * Build the issue create or update body.
 */
export function buildIssuePayload(
  event: WorkflowRunEvent,
  existingIssue?: ExistingIssueSummary | null
): { action: "create" | "update"; title: string; body: string; issueNumber?: number } {
  const title = buildCronFailureDedupeKey(event.workflowName, event.createdAt);

  if (!existingIssue) {
    const body = [
      `### Cron Workflow Failure Alert`,
      ``,
      `- **Workflow**: \`${event.workflowName}\``,
      `- **Conclusion**: \`${event.conclusion}\``,
      `- **Run URL**: ${event.runUrl}`,
      `- **Run ID**: \`${event.runId}\``,
      `- **Timestamp**: ${event.createdAt}`,
      ``,
      `*Automated failure alert generated by workflow-failure-alert.yml.*`,
    ].join("\n");
    return { action: "create", title, body };
  }

  // Deduplicate run URL in body if already present
  let body = existingIssue.body || "";
  if (!body.includes(event.runUrl)) {
    body += `\n\n- Additional failure at ${event.createdAt}: ${event.runUrl}`;
  }
  return {
    action: "update",
    title,
    body,
    issueNumber: existingIssue.number,
  };
}

/**
 * Main decision runner for workflow_run completion events.
 * Fail-open by design: errors in alert dispatch never throw.
 */
export async function processWorkflowAlert(
  event: WorkflowRunEvent,
  deps: WorkflowAlertDeps = {}
): Promise<WorkflowAlertResult> {
  const dedupeKey = buildCronFailureDedupeKey(event.workflowName, event.createdAt);

  // 1. Filter: conclusion must be 'failure'
  if (event.conclusion !== "failure") {
    return {
      eligible: false,
      skippedReason: `Conclusion '${event.conclusion}' is not a failure`,
      sentryDispatched: false,
      issueAction: "none",
      dedupeKey,
      issueTitle: dedupeKey,
    };
  }

  // 2. Filter: workflow must be in the scheduled cron allowlist
  if (!isScheduledCronWorkflow(event.workflowName)) {
    return {
      eligible: false,
      skippedReason: `Workflow '${event.workflowName}' is not in the scheduled cron allowlist`,
      sentryDispatched: false,
      issueAction: "none",
      dedupeKey,
      issueTitle: dedupeKey,
    };
  }

  // 3. Dispatch Sentry captureMessage (fail-open)
  let sentryDispatched = false;
  try {
    const { cronTag, message, extra } = buildSentryAlertMessage(event);
    const sentryFn = deps.sendSentryAlert || reportCronFailureMessage;
    await sentryFn(cronTag, message, extra);
    sentryDispatched = true;
  } catch (err) {
    console.error(`[workflow-failure-alert] Sentry dispatch failed (fail-open):`, err);
  }

  // 4. Create or update deduped GitHub issue (fail-open)
  let issueAction: "created" | "updated" | "none" = "none";
  try {
    const existing = deps.findExistingIssue ? await deps.findExistingIssue(dedupeKey) : null;
    const payload = buildIssuePayload(event, existing);

    if (payload.action === "create" && deps.createIssue) {
      await deps.createIssue(payload.title, payload.body);
      issueAction = "created";
    } else if (payload.action === "update" && deps.updateIssue && payload.issueNumber) {
      await deps.updateIssue(payload.issueNumber, payload.body);
      issueAction = "updated";
    }
  } catch (err) {
    console.error(`[workflow-failure-alert] GitHub issue operation failed (fail-open):`, err);
  }

  return {
    eligible: true,
    sentryDispatched,
    issueAction,
    dedupeKey,
    issueTitle: dedupeKey,
  };
}
